// ==========================================
// オーダーシート解析
// ==========================================

function parseOrder(text) {

    const result = [];


    const regex =
        /([^,\[\]]+?)\s*-\s*\[\s*([^\]]*?)\s*\](?:,|$)/g;


    let match;


    while (
        (
            match =
                regex.exec(text)
        ) !== null
    ) {

        const name =
            match[1]
                .trim();


        const detail =
            match[2]
                .trim();


        if (!name) {

            continue;
        }


        result.push({

            category:
                getCategory(
                    name,
                    detail
                ),

            name,

            detail
        });
    }


    return result;
}
