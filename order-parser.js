// ==========================================
// カラー項目判定
// ==========================================

function isColorItem(name, detail) {

    const colorNames = [

        "メインカラー",

        "サブカラー",

        "プライマリ",

        "セカンダリー",

        "パール",

        "パールセント",

        "ホイールカラー",

        "インテリア",

        "内装"
    ];


    if (
        colorNames.includes(name)
    ) {

        return true;
    }


    // Wheelsはホイール本体
    // ホイールはカラー

    if (
        name === "ホイール"
    ) {

        return true;
    }


    // ダッシュボードは
    // パーツ変更とカラー変更が存在

    if (
        name === "ダッシュボード"
    ) {

        const colorWords =
            /メタリック|マット|クローム|金属|パール|カラー|ブラック|ホワイト|レッド|ブルー|グリーン|イエロー|オレンジ|パープル|ピンク|シルバー|ゴールド|グレー/i;


        if (
            colorWords.test(detail)
        ) {

            return true;
        }
    }


    return false;
}


